// TestGenGoCompilesAndRuns は生成した Go を実際にビルドして実行し、
// EvalFloat64 と同じ値が出ることを確かめる。コード生成の端から端までの検査。
func TestGenGoCompilesAndRuns(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: go build を走らせるので飛ばす")
	}
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go コマンドが見つからない")
	}

	tp := inv2()
	dir := t.TempDir()

	var gen bytes.Buffer
	if err := GenGo(&gen, tp, GoOptions{Package: "main", Func: "inv2"}); err != nil {
		t.Fatalf("GenGo: %v", err)
	}
	write := func(name, content string) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// このリポジトリの go.mod と同じ版にしておく。ここだけ新しくすると、
	// 古い Go を使っている人がテストを走らせたときにここだけ失敗する。
	write("go.mod", "module gentest\n\ngo 1.22\n")
	write("inv2.go", gen.String())
	write("main.go", `package main

import "fmt"

func main() {
	v := []float64{4, 1, 2}
	out := make([]float64, 3)
	inv2(v, out)
	for _, x := range out {
		fmt.Printf("%v\n", x)
	}
}
`)

	cmd := exec.Command("go", "run", ".")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run: %v\n%s", err, out)
	}

	want := make([]float64, 3)
	EvalFloat64(tp, []float64{4, 1, 2}, NewScratch[float64](tp), want)

	lines := strings.Fields(strings.TrimSpace(string(out)))
	if len(lines) != 3 {
		t.Fatalf("出力が3行でない: %q", out)
	}
	for i, line := range lines {
		got, err := strconv.ParseFloat(line, 64)
		if err != nil {
			t.Fatalf("%d 行目 %q: %v", i, line, err)
		}
		if math.Abs(got-want[i]) > 1e-15 {
			t.Errorf("out[%d]: 生成コード %v, EvalFloat64 %v", i, got, want[i])
		}
	}
}

// TestGenGoPrunes は、死んだ命令があっても生成物がコンパイルできることを
// 確かめる。Go は使われない局所変数をエラーにするので、Prune が効いていないと
// go/format は通っても実際のビルドで落ちる。
func TestGenGoPrunes(t *testing.T) {
	tp := inv2()
	tp.Instrs = append(tp.Instrs, Bin(OpMul, 0, 1))
	var buf bytes.Buffer
	if err := GenGo(&buf, tp, GoOptions{Package: "p", Func: "F"}); err != nil {
		t.Fatalf("GenGo: %v", err)
	}
	if n := strings.Count(buf.String(), ":="); n != 8 {
		t.Errorf("局所変数の数 = %d, want 8:\n%s", n, buf.String())
	}
}

