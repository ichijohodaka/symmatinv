func TestPruneDropsDeadInstrs(t *testing.T) {
	tp := inv2()
	// 出力に寄与しない命令を2つ足す。
	tp.Instrs = append(tp.Instrs,
		Bin(OpMul, 0, 1), // slot 11 — 誰も読まない
		Un(OpNeg, 11),    // slot 12 — 上を読むが、やはり誰も読まない
	)
	if err := tp.Validate(); err != nil {
		t.Fatalf("Validate: %v", err)
	}

	got := tp.Prune()
	if err := got.Validate(); err != nil {
		t.Fatalf("Prune 後の Validate: %v", err)
	}
	if got.NumInstrs() != 8 {
		t.Errorf("Prune 後の命令数 = %d, want 8", got.NumInstrs())
	}
	if tp.NumInstrs() != 10 {
		t.Errorf("Prune が元の命令列を壊した (命令数 %d)", tp.NumInstrs())
	}

	// 値が変わらないこと。
	vars := []float64{4, 1, 2}
	before := make([]float64, 3)
	EvalFloat64(tp, vars, NewScratch[float64](tp), before)
	after := make([]float64, 3)
	EvalFloat64(got, vars, NewScratch[float64](got), after)
	for i := range before {
		if before[i] != after[i] {
			t.Errorf("out[%d]: Prune 前 %v, 後 %v", i, before[i], after[i])
		}
	}
}

// TestPruneKeepsUnusedVars は、使われていない入力変数が残ることを確かめる。
// 変数の並びは外向きの取り決めなので、勝手に詰めてはいけない。
func TestPruneKeepsUnusedVars(t *testing.T) {
	tp := &Tape{
		NumVars: 3,
		Instrs:  []Instr{Bin(OpAdd, 0, 2)}, // v1 を使わない
		Outputs: []int32{3},
	}
	got := tp.Prune()
	if got.NumVars != 3 {
		t.Errorf("NumVars = %d, want 3", got.NumVars)
	}
	if got.Instrs[0].A != 0 || got.Instrs[0].B != 2 {
		t.Errorf("変数のスロット番号が変わった: %+v", got.Instrs[0])
	}
}

func TestGenGoText(t *testing.T) {
	var buf bytes.Buffer
	err := GenGo(&buf, inv2(), GoOptions{Package: "mypkg", Func: "Inv2"})
	if err != nil {
		t.Fatalf("GenGo: %v", err)
	}
	s := buf.String()
	for _, want := range []string{
		"// Code generated by symmatinv. DO NOT EDIT.",
		"package mypkg",
		"func Inv2(v, out []float64) {",
		"t0 := v[0] * v[2]",
		"t3 := 1 / t2",
		"t6 := -t5",
		"out[0] = t4 // b00",
		"1回あたりの演算回数: 8 (sub 1, mul 5, neg 1, recip 1)",
		"a00, a01, a11",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("生成結果に %q がない:\n%s", want, s)
		}
	}
}

